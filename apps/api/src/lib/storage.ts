import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import { config } from '../config';

/**
 * Where uploaded files live. Only this interface is used by the app, so the
 * local-disk implementation can be swapped for S3 (or similar) later.
 * Files are write-once: a key is never overwritten or deleted.
 */
export interface FileStorage {
  readonly driver: string;
  put(key: string, data: Buffer): Promise<void>;
  get(key: string): Promise<Buffer>;
}

export class LocalDiskStorage implements FileStorage {
  readonly driver = 'local';
  private readonly root: string;

  constructor(root: string) {
    this.root = resolve(root);
  }

  private pathFor(key: string) {
    const path = resolve(this.root, key);
    // keys are generated by us, but never let one escape the storage folder
    if (!path.startsWith(this.root + sep)) throw new Error(`Invalid storage key: ${key}`);
    return path;
  }

  async put(key: string, data: Buffer) {
    const path = this.pathFor(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, data, { flag: 'wx' });
  }

  get(key: string) {
    return readFile(this.pathFor(key));
  }
}

export const storage: FileStorage = new LocalDiskStorage(config.UPLOAD_DIR);
